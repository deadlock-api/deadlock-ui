/**
 * Fetches all item and hero class names from the Deadlock API and generates:
 * 1. TypeScript union types for autocomplete
 *    (packages/core/src/types/item-class-name.ts, packages/core/src/types/hero-class-name.ts)
 * 2. JSON catalog for docs (docs/src/data/items.json)
 *
 * The hero union is open-ended ((string & {})) so newly released heroes work
 * without regenerating: runtime data always comes straight from the API.
 *
 * Usage: node scripts/generate-class-names.mjs
 */

import repoConfig from '../repo.config.mjs';

const ITEMS_API_URL = repoConfig.apiItemsUrl;
const HEROES_API_URL = repoConfig.apiHeroesUrl;
const ITEM_TYPE_OUTPUT = new URL('../packages/core/src/types/item-class-name.ts', import.meta.url);
const HERO_TYPE_OUTPUT = new URL('../packages/core/src/types/hero-class-name.ts', import.meta.url);
const ITEMS_JSON_OUTPUT = new URL('../docs/src/data/items.json', import.meta.url);

const { writeFileSync, mkdirSync } = await import('node:fs');
const { fileURLToPath } = await import('node:url');
const { dirname } = await import('node:path');

function writeUnionType(output, typeName, classNames, { openEnded = false } = {}) {
  const members = classNames.map((n) => `  | '${n}'`);
  if (openEnded) members.push('  | (string & {})');
  const tsLines = [
    '// Auto-generated by scripts/generate-class-names.mjs - do not edit manually.',
    '',
    `export type ${typeName} =`,
    members.join('\n') + ';',
    '',
  ];
  writeFileSync(fileURLToPath(output), tsLines.join('\n'));
}

async function fetchJson(url) {
  const res = await fetch(url);
  if (!res.ok) throw new Error(`API request failed: ${res.status}`);
  return res.json();
}

// --- Items ---
const allItems = await fetchJson(ITEMS_API_URL);
const items = allItems.filter((i) => i.type === 'upgrade' && i.shopable);

const itemClassNames = items.map((i) => i.class_name).sort();
writeUnionType(ITEM_TYPE_OUTPUT, 'ItemClassName', itemClassNames);

const itemsCatalog = items
  .map((i) => ({
    class_name: i.class_name,
    name: i.name,
    type: i.type,
    item_slot_type: i.item_slot_type,
    item_tier: i.item_tier,
    image: i.shop_image_webp || i.shop_image || i.image_webp || i.image || null,
  }))
  .sort((a, b) => a.class_name.localeCompare(b.class_name));

const itemsJsonPath = fileURLToPath(ITEMS_JSON_OUTPUT);
mkdirSync(dirname(itemsJsonPath), { recursive: true });
writeFileSync(itemsJsonPath, JSON.stringify(itemsCatalog, null, 2) + '\n');

console.log(`Generated ${itemClassNames.length} class names -> packages/core/src/types/item-class-name.ts`);
console.log(`Generated ${itemsCatalog.length} items catalog  -> docs/src/data/items.json`);

// --- Heroes ---
const allHeroes = await fetchJson(HEROES_API_URL);

const heroClassNames = allHeroes.map((h) => h.class_name).sort();
writeUnionType(HERO_TYPE_OUTPUT, 'HeroClassName', heroClassNames, { openEnded: true });

console.log(`Generated ${heroClassNames.length} class names -> packages/core/src/types/hero-class-name.ts`);
